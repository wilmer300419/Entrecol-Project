-- V002: módulo BASE-ENTRETENIMIENTO (películas y libros) en 3FN
CREATE TABLE genero (
    id_genero SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE pelicula (
    id_pelicula  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(300) NOT NULL,
    anio_estreno SMALLINT CHECK (anio_estreno BETWEEN 1870 AND 2100)
);
CREATE INDEX ix_pelicula_anio ON pelicula (anio_estreno);

CREATE TABLE pelicula_genero (
    id_pelicula INTEGER  NOT NULL REFERENCES pelicula (id_pelicula) ON UPDATE CASCADE ON DELETE CASCADE,
    id_genero   SMALLINT NOT NULL REFERENCES genero (id_genero) ON UPDATE CASCADE ON DELETE RESTRICT,
    PRIMARY KEY (id_pelicula, id_genero)
);
CREATE INDEX ix_pelicula_genero_genero ON pelicula_genero (id_genero);

CREATE TABLE idioma (
    codigo_idioma VARCHAR(10) PRIMARY KEY
);

CREATE TABLE editorial (
    id_editorial INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(300) NOT NULL UNIQUE
);

CREATE TABLE autor (
    id_autor INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(400) NOT NULL UNIQUE
);

CREATE TABLE libro (
    id_libro                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(600) NOT NULL,
    isbn                    VARCHAR(10),
    isbn13                  VARCHAR(13) UNIQUE,
    codigo_idioma           VARCHAR(10) REFERENCES idioma (codigo_idioma) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_editorial            INTEGER REFERENCES editorial (id_editorial) ON UPDATE CASCADE ON DELETE RESTRICT,
    num_paginas             INTEGER CHECK (num_paginas >= 0),
    calificacion_promedio   NUMERIC(3,2) NOT NULL DEFAULT 0 CHECK (calificacion_promedio BETWEEN 0 AND 5),
    cantidad_calificaciones INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_calificaciones >= 0),
    cantidad_resenas        INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_resenas >= 0),
    fecha_publicacion       DATE
);
CREATE INDEX ix_libro_fecha ON libro (fecha_publicacion);
CREATE INDEX ix_libro_calificacion ON libro (calificacion_promedio DESC);

CREATE TABLE libro_autor (
    id_libro INTEGER  NOT NULL REFERENCES libro (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    id_autor INTEGER  NOT NULL REFERENCES autor (id_autor) ON UPDATE CASCADE ON DELETE RESTRICT,
    orden    SMALLINT NOT NULL DEFAULT 1 CHECK (orden > 0),
    PRIMARY KEY (id_libro, id_autor)
);
CREATE INDEX ix_libro_autor_autor ON libro_autor (id_autor);
